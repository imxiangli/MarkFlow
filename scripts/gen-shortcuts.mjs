/** Escape Markdown punctuation that appears in key names (`, \, [, ], |). */
const esc = (s) => s.replace(/[\\`[\]|*_]/g, '\\$&')

function cell(keys, kbd, or) {
  if (!keys.length) return ''
  return keys.map((k) => (kbd ? `<kbd>${esc(k)}</kbd>` : esc(k))).join(or)
}

/** Table rows; numbered series (headings, tabs, fold levels) collapse into one row. */
function rows(locale, ids) {
  const t = TEXT[locale]
  const out = []
  const defs = ids ? ids.map((id) => COMMAND_MAP.get(id)) : COMMANDS
  for (let i = 0; i < defs.length; i++) {
    const def = defs[i]
    const keys = (p) => keysOf(def, p).map((k) => displayKey(k, p))
    if (!keysOf(def, 'darwin').length && !keysOf(def, 'win32').length) continue
    if (def.labelVars?.n === 1) {
      const series = [def]
      while (defs[i + 1]?.label === def.label && defs[i + 1]?.labelVars?.n === series.length + 1) series.push(defs[++i])
      const visible = series.filter((d) => !d.hidden)
      const last = visible[visible.length - 1]
      const span = (p) => `${displayKey(keysOf(def, p)[0], p)} … ${displayKey(keysOf(last, p)[0], p)}`
      out.push({
        label: translate(locale, def.label, { n: `1–${last.labelVars.n}` }),
        mac: [span('darwin')],
        other: [span('win32')]
      })
      continue
    }
    out.push({
      label: translate(locale, def.label, def.labelVars) + (def.id.startsWith('find-toggle-') ? t.findField : ''),
      group: def.group,
      mac: keys('darwin'),
      other: keys('win32')
    })
  }
  return out
}

function table(locale, list, kbd) {
  const t = TEXT[locale]
  const lines = [`| ${t.command} | ${t.mac} | ${t.other} |`, '| --- | --- | --- |']
  for (const r of list) lines.push(`| ${esc(r.label)} | ${cell(r.mac, kbd, t.or)} | ${cell(r.other, kbd, t.or)} |`)
  return lines.join('\n')
}

function fullDoc(locale) {
  const t = TEXT[locale]
  const all = rows(locale)
  const groups = []
  for (const def of COMMANDS) if (!groups.includes(def.group)) groups.push(def.group)
  const parts = [t.title, '', ...t.intro]
  for (const g of groups) {
    const ids = COMMANDS.filter((d) => d.group === g).map((d) => d.id)
    const list = rows(locale, ids)
    if (!list.length) continue
    parts.push('', `## ${translate(locale, g)}`, '', table(locale, list, false))
  }
  void all
  return parts.join('\n') + '\n'
}

