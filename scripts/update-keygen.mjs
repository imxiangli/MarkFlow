// Generates the Ed25519 key pair used to sign update manifests.
//   node scripts/update-keygen.mjs [--force]
// The private key stays in keys/ (git-ignored) — back it up: installed apps only accept
// updates signed with it. The public key is compiled into the app.
import { generateKeyPairSync } from 'node:crypto'
import { existsSync, mkdirSync, writeFileSync, chmodSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const privPath = join(root, 'keys/update-private.pem')
const pubTs = join(root, 'src/main/update-public-key.ts')

if (existsSync(privPath) && !process.argv.includes('--force')) {
  console.error(`${privPath} already exists. Re-run with --force to replace it (existing installs will reject new updates).`)
  process.exit(1)
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519')
mkdirSync(dirname(privPath), { recursive: true })
writeFileSync(privPath, privateKey.export({ type: 'pkcs8', format: 'pem' }))
chmodSync(privPath, 0o600)
const pem = publicKey.export({ type: 'spki', format: 'pem' }).toString().trim()
writeFileSync(
  pubTs,
  `// Generated by scripts/update-keygen.mjs — public half of the update signing key.\nexport const UPDATE_PUBLIC_KEY = \`${pem}\`\n`
)
console.log(`private key: ${privPath}\npublic key:  ${pubTs}`)
