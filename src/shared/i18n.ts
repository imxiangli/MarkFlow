export const messages: Record<Locale, Record<MessageKey, string>> = { 'zh-CN': zh, en }

export function resolveLocale(setting: LanguageSetting, systemLocale: string): Locale {
  if (setting === 'zh-CN' || setting === 'en') return setting
  return systemLocale.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = messages[locale][key] ?? messages.en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  }
  return s
}
